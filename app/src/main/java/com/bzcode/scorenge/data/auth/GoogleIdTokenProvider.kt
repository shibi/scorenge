package com.bzcode.scorenge.data.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.bzcode.scorenge.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import javax.inject.Inject

/** Shows the Google account picker and returns the chosen account's ID token. */
interface GoogleIdTokenProvider {
    /** @param activityContext an Activity context; Credential Manager shows its UI over it. */
    suspend fun requestIdToken(activityContext: Context): String
}

class CredentialManagerGoogleIdTokenProvider @Inject constructor() : GoogleIdTokenProvider {
    override suspend fun requestIdToken(activityContext: Context): String {
        // default_web_client_id is generated by the google-services plugin from the Web OAuth
        // client in google-services.json (created when Google sign-in is enabled in Firebase).
        val option = GetSignInWithGoogleOption.Builder(activityContext.getString(R.string.default_web_client_id)).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            return GoogleIdTokenCredential.createFrom(credential.data).idToken
        }
        throw IllegalStateException("Unexpected credential type: ${credential.type}")
    }
}
