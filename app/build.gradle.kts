android {
    namespace = "com.bzcode.scorenge"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.bzcode.scorenge"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        getByName("debug") {
            // Shared project debug key, so every debug build has the SHA-1 registered in Firebase.
            // Not in git: CI writes it from the DEBUG_KEYSTORE_BASE64 secret; locally, copy it to
            // app/debug.keystore. Without it, the machine's default debug key is used.
            val shared = file("debug.keystore")
            if (shared.exists()) {
                storeFile = shared
                storePassword = "android"
                keyAlias = "androiddebugkey"
                keyPassword = "android"
            }
        }
        // Play upload key. Not in git: CI writes it from the RELEASE_KEYSTORE_BASE64 secret and passes
        // the password in RELEASE_KEYSTORE_PASSWORD. Without them the release build is left unsigned.
        val uploadKey = file("release.keystore")
        val uploadPassword = System.getenv("RELEASE_KEYSTORE_PASSWORD")
        if (uploadKey.exists() && !uploadPassword.isNullOrEmpty()) {
            create("release") {
                storeFile = uploadKey
                storePassword = uploadPassword
                keyAlias = "scorenge-upload"
                keyPassword = uploadPassword
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

